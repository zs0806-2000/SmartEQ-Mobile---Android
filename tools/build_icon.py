#!/usr/bin/env python3
"""Builds the app icon resources from the T3 artwork. Needs rsvg-convert.
Run: python3 tools/build_icon.py"""
import math, subprocess, os
OUT=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','design','icon')
RES=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','app','src','main','res')
PEACH,BLUSH,LILAC,BG='#FFB599','#F7B7C6','#CDB9F2','#141113'

def hemi_pts(side,gap=1.6,cx=54,cy=54,RX=26,RY=31,N=72):
    pts=[]
    for i in range(N+1):
        phi=-math.pi/2+math.pi*i/N
        taper=0.80+0.20*(1+math.sin(phi))/2
        bump=1+0.05*math.sin(11*(phi+1.9))
        r=RX*taper*bump
        x=cx-gap-r*math.cos(phi)**0.8
        y=cy+RY*math.sin(phi)*(1+0.02*math.sin(9*phi))
        if side>0: x=2*cx-x
        pts.append((x,y))
    return pts
SLOTS=[(7,38),(12.5,46),(18,52)]  # (offset from centre, top); right side tops +3
def glyph_parts(scale):
    """Return (hemisphere polygons, slot pills) scaled about the centre."""
    S=lambda x,y:(54+(x-54)*scale,54+(y-54)*scale)
    hemis=[[S(x,y) for x,y in hemi_pts(s)] for s in (-1,1)]
    slots=[]
    for side in (-1,1):
        for o,top in SLOTS:
            x=54+side*o; t=top+(3 if side>0 else 0)
            x0,y0=S(x-1.7,t); x1,y1=S(x+1.7,73)
            slots.append((x0,y0,x1,y1))
    return hemis,slots
def max_radius(scale):
    h,_=glyph_parts(scale); return max(math.hypot(x-54,y-54) for p in h for x,y in p)
# Fit the outline inside the adaptive-icon safe zone (radius 33 of 108) with a small margin.
scale=1.0
while max_radius(scale)>31.5: scale-=0.005
def path_data(scale):
    hemis,slots=glyph_parts(scale)
    d=''
    for p in hemis: d+='M'+' L'.join(f'{x:.2f},{y:.2f}' for x,y in p)+' Z '
    for x0,y0,x1,y1 in slots:
        r=(x1-x0)/2
        d+=f'M{x0:.2f},{y0+r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x1:.2f},{y0+r:.2f} L{x1:.2f},{y1-r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0:.2f},{y1-r:.2f} Z '
    return d.strip()
D=path_data(scale)

AA='xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"'
def grad_fill():
    return f'''        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="30" android:startY="24" android:endX="80" android:endY="86">
                <item android:offset="0" android:color="#FF{PEACH[1:]}" />
                <item android:offset="0.55" android:color="#FF{BLUSH[1:]}" />
                <item android:offset="1" android:color="#FF{LILAC[1:]}" />
            </gradient>
        </aapt:attr>'''
hdr='''<?xml version="1.0" encoding="utf-8"?>
<!-- SmartyQ icon, concept T3 "Bands cut into the brain" (approved 2026-11-21).
     A top-down brain whose EQ bands are negative space. Generated by tools/build_icon.py;
     edit that script, not this file. Fits the 66 dp adaptive-icon safe zone. -->
'''
fg=hdr+f'''<vector {AA}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillType="evenOdd"
        android:pathData="{D}">
{grad_fill()}
    </path>
</vector>
'''
bg=hdr+f'''<vector {AA}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FF{BG[1:]}" android:pathData="M0,0h108v108h-108z" />
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="24" android:centerY="20" android:gradientRadius="80">
                <item android:offset="0" android:color="#2EFFB599" />
                <item android:offset="1" android:color="#00FFB599" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
mono=hdr+f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF"
        android:pathData="{D}" />
</vector>
'''
# Notification icon: 24 dp, white silhouette; same artwork mapped from the 108 grid.
nscale=24/ (2*max_radius(scale)+2)
notif=hdr+f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="108" android:viewportHeight="108"
    android:tint="#FFFFFFFF">
    <group android:pivotX="54" android:pivotY="54" android:scaleX="{108/(2*max_radius(scale)+4):.3f}" android:scaleY="{108/(2*max_radius(scale)+4):.3f}">
        <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF"
            android:pathData="{D}" />
    </group>
</vector>
'''
open(f'{RES}/drawable/ic_launcher_foreground.xml','w').write(fg)
open(f'{RES}/drawable/ic_launcher_background.xml','w').write(bg)
open(f'{RES}/drawable/ic_launcher_monochrome.xml','w').write(mono)
open(f'{RES}/drawable/ic_notification_fader.xml','w').write(notif)

# Same artwork as SVG for PNG exports (legacy mipmaps, Play Store 512 px) and previews.
def svg(size, shape='square'):
    clip={'square':'','circle':'<clipPath id="k"><circle cx="54" cy="54" r="54"/></clipPath>','squircle':'<clipPath id="k"><rect width="108" height="108" rx="26"/></clipPath>'}[shape]
    cp='' if shape=='square' else ' clip-path="url(#k)"'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108"><defs>{clip}
<linearGradient id="g" gradientUnits="userSpaceOnUse" x1="30" y1="24" x2="80" y2="86"><stop offset="0" stop-color="{PEACH}"/><stop offset=".55" stop-color="{BLUSH}"/><stop offset="1" stop-color="{LILAC}"/></linearGradient>
<radialGradient id="p" gradientUnits="userSpaceOnUse" cx="24" cy="20" r="80"><stop offset="0" stop-color="{PEACH}" stop-opacity=".18"/><stop offset="1" stop-color="{PEACH}" stop-opacity="0"/></radialGradient></defs>
<g{cp}><rect width="108" height="108" fill="{BG}"/><rect width="108" height="108" fill="url(#p)"/><path fill-rule="evenodd" fill="url(#g)" d="{D}"/></g></svg>'''
os.makedirs(OUT,exist_ok=True)
for name,px in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
    for fn,shape in [('ic_launcher','squircle'),('ic_launcher_round','circle')]:
        open('/tmp/i.svg','w').write(svg(px,shape))
        os.makedirs(f'{RES}/mipmap-{name}',exist_ok=True)
        subprocess.run(['rsvg-convert','-w',str(px),'-h',str(px),'/tmp/i.svg','-o',f'{RES}/mipmap-{name}/{fn}.png'],check=True)
open('/tmp/i.svg','w').write(svg(512,'square'))
subprocess.run(['rsvg-convert','-w','512','-h','512','/tmp/i.svg','-o',''+OUT+'/play-store-icon-512.png'],check=True)
open(''+OUT+'/smarteq-icon.svg','w').write(svg(1024,'square'))
print(f'scale={scale:.3f} maxR={max_radius(scale):.2f}')
